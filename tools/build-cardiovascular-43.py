#!/usr/bin/env python3
"""Build local, self-hostable BodyParts3D 4.3 cardiovascular GLBs.

Requires `python3 -m pip install trimesh numpy fast-simplification`. Reads the
MANIFEST.csv and actual downloaded OBJ files generated by upstream subset tool.
Never silently invents or substitutes an anatomical mesh.
"""
import argparse
import csv
import hashlib
import json
import re
import sys
from pathlib import Path

import numpy as np
import trimesh

SOURCE_Y_MIN = -3.534865
SOURCE_HEIGHT = 3.183290 - SOURCE_Y_MIN
SOURCE_Z_CENTER = 0.4
LEGACY_CARDIO_IDS = [x.strip() for x in (Path(__file__).parent/'cardio-original-ids.txt').read_text().splitlines() if x.strip() and not x.startswith('#')]


def read_rows(folders, prior_manifest=None):
    rows = {}
    for directory in folders:
        manifest = directory / 'MANIFEST.csv'
        if not manifest.is_file():
            raise SystemExit(f'Missing validated subset manifest: {manifest}')
        with manifest.open(newline='') as file:
            for row in csv.DictReader(file):
                fj = row['fj_id']
                if not re.fullmatch(r'FJ\d+[A-Z]?', fj):
                    raise SystemExit(f'Unrecognized FJ identifier: {fj}')
                obj = directory / row['obj']
                if not obj.is_file() or obj.stat().st_size < 300:
                    raise SystemExit(f'Missing or incomplete downloaded mesh: {obj}')
                if fj in rows:
                    raise SystemExit(f'Duplicate cardiovascular FJ identifier: {fj}')
                rows[fj] = (row, obj)
    if not rows:
        raise SystemExit('No real OBJ geometry found; nothing to convert.')
    # BodyParts3D includes IDs such as FJ1682 and FJ1682M (distinct meshes).
    # Sort numerically, then by suffix, without collapsing the paired IDs.
    def fj_sort_key(fj):
        match = re.fullmatch(r'FJ(\d+)([A-Z]?)', fj)
        return (int(match.group(1)), match.group(2))
    # Preserve *exactly* the old 1.5.1 15-mesh order, even when adding
    # lower-numbered new IDs. Scene labels/colors are indexed by mesh order.
    legacy = [k for k in LEGACY_CARDIO_IDS if k in rows]
    if legacy and len(legacy) != len(LEGACY_CARDIO_IDS):
        raise SystemExit('Cannot safely rebuild old scenes: original cardiovascular subset is incomplete.')
    if prior_manifest and prior_manifest.is_file():
        # The teacher's saved lessons use a flat structure index. Previous
        # 1.8 meshes must retain *all* old indices, not just the first 15.
        previous = json.loads(prior_manifest.read_text())
        prior_ids = [v['id'] for v in previous.get('structures',[])]
        if len(prior_ids)!=len(set(prior_ids)) or any(k not in rows for k in prior_ids):
            raise SystemExit('Existing cardiovascular model contains IDs missing from the source inputs; refusing incompatible rebuild.')
        if prior_ids[:len(LEGACY_CARDIO_IDS)] != LEGACY_CARDIO_IDS:
            raise SystemExit('Existing cardiovascular model has unexpected original mesh order; refusing incompatible rebuild.')
        extra=sorted((k for k in rows if k not in prior_ids),key=fj_sort_key)
        return [rows[k] for k in prior_ids+extra]
    extra=sorted((k for k in rows if k not in LEGACY_CARDIO_IDS),key=fj_sort_key)
    return [rows[k] for k in legacy+extra]


def load_mesh(path):
    raw = trimesh.load(path, force='scene', process=False)
    meshes = [g for g in raw.geometry.values() if isinstance(g, trimesh.Trimesh) and len(g.faces)]
    if not meshes:
        raise ValueError(f'Empty or invalid anatomical mesh: {path}')
    if len(meshes) == 1:
        return meshes[0]
    return trimesh.util.concatenate(meshes)


def normalizer(skin, axis='auto', invert=False):
    lo, hi = skin.bounds
    axis_i = int(np.argmax(hi-lo)) if axis == 'auto' else 'xyz'.index(axis)
    if axis_i != int(np.argmax(hi-lo)):
        print('WARNING: chosen vertical axis is not the largest skin axis', file=sys.stderr)
    horizontal = [i for i in range(3) if i != axis_i]
    scale = SOURCE_HEIGHT / float(hi[axis_i]-lo[axis_i])
    midpoint = (hi+lo)*0.5
    def transform(verts):
        result = np.empty_like(verts, dtype=np.float64)
        result[:, 0] = (verts[:, horizontal[0]] - midpoint[horizontal[0]]) * scale
        upward = hi[axis_i]-verts[:, axis_i] if invert else verts[:, axis_i]-lo[axis_i]
        result[:, 1] = upward*scale+SOURCE_Y_MIN
        result[:, 2] = (verts[:, horizontal[1]] - midpoint[horizontal[1]])*scale+SOURCE_Z_CENTER
        return result
    return transform, {'vertical_axis': 'xyz'[axis_i], 'inverted': bool(invert), 'scale': scale}


def reduce(mesh, limit):
    if len(mesh.faces) <= limit:
        return mesh.copy()
    try:
        return mesh.simplify_quadric_decimation(face_count=limit)
    except Exception as e:
        # Never claim a mesh has been optimized when its original geometry was retained.
        raise RuntimeError(f'Simplification failed for {len(mesh.faces):,} faces. '
            'Install fast-simplification, or increase --standard-faces. '+str(e)) from e


def glb(scene, target):
    target.parent.mkdir(parents=True, exist_ok=True)
    temp = target.with_suffix('.glb.part')
    temp.write_bytes(scene.export(file_type='glb'))
    # Check GLB magic and document bytes; full verification below.
    if temp.read_bytes()[:4] != b'glTF':
        raise SystemExit('GLB export produced invalid bytes')
    temp.replace(target)


def build(folders, skin_file, out, standard_faces, detail_faces, axis, invert, extra_standard_faces=3200, extra_detailed_faces=11000, prior_manifest=None):
    skin = load_mesh(skin_file)
    transform, reg = normalizer(skin, axis=axis, invert=invert)
    rows = read_rows(folders, prior_manifest)
    normal_scene = trimesh.Scene(); detailed_scene = trimesh.Scene()
    manifest=[]; total_standard=total_detail=0
    for row, path in rows:
        source = load_mesh(path)
        source.vertices = transform(np.asarray(source.vertices))
        # Discard corrupt/degenerate structures; fail instead of manufacturing geometry.
        if not np.isfinite(source.vertices).all() or len(source.faces) < 5:
            raise SystemExit(f'Invalid anatomical geometry: {path}')
        is_legacy = row['fj_id'] in LEGACY_CARDIO_IDS
        standard = reduce(source, standard_faces if is_legacy else extra_standard_faces)
        detailed = reduce(source, detail_faces if is_legacy else extra_detailed_faces)
        for mesh in (standard, detailed):
            mesh.remove_unreferenced_vertices()
            # Recompute smooth vertex normals after simplification.
            _ = mesh.vertex_normals
        node = row['fj_id']
        normal_scene.add_geometry(standard, geom_name=node, node_name=node)
        detailed_scene.add_geometry(detailed, geom_name=node, node_name=node)
        total_standard += len(standard.faces); total_detail += len(detailed.faces)
        manifest.append({'id':node,'fma_id':row['fma_id'],'name':row['name'],
          'standard_triangles':len(standard.faces),'detailed_triangles':len(detailed.faces),
          'category':row.get('category') or ('heart' if 'wall of' in row['name'].lower() else 'major-vessel')})
        print(f'{node:9} {row["name"][:44]:44} {len(standard.faces):>7,}/{len(detailed.faces):>7,} triangles')
    if len(manifest)<10:
        raise SystemExit('Too few actual structures for the detailed cardiovascular release (minimum 10).')
    out.mkdir(parents=True, exist_ok=True)
    glb(normal_scene, out/'cardiovascular-standard.glb')
    glb(detailed_scene, out/'cardiovascular-detailed.glb')
    metadata={'version':1,'source':'BodyParts3D / DBCLS 4.3','license':'CC BY-SA 2.1 Japan',
      'coordinate_frame':'BodyParts3D skin-normalized to Anatomy Studio 1.2 body frame',
      'registration':reg,'structures':manifest}
    (out/'cardiovascular-structures.json').write_text(json.dumps(metadata,indent=2)+'\n')
    for name in ['cardiovascular-standard.glb','cardiovascular-detailed.glb']:
        path=out/name
        if path.stat().st_size>95_000_000:
            raise SystemExit(f'{name} is over 95 MB; re-run with smaller --detailed-faces to keep GitHub hosting practical.')
        loaded=trimesh.load(path,force='scene')
        if len(loaded.graph.nodes_geometry)!=len(manifest):
            raise SystemExit(f'GLB verification failed: expected {len(manifest)} objects in {name}')
    print(f'Validated {len(manifest)} structures. Standard {total_standard:,}, Detailed {total_detail:,} triangles.')
    for name in ['cardiovascular-standard.glb','cardiovascular-detailed.glb','cardiovascular-structures.json']:
        path=out/name
        print(f'{path}: {path.stat().st_size/1024/1024:.2f} MB SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}')


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--subset',action='append',required=True,type=Path,help='Subset output folder containing MANIFEST.csv (repeatable)')
    p.add_argument('--skin',required=True,type=Path,help='Downloaded BodyParts3D skin OBJ used for common-body registration')
    p.add_argument('--out',default=Path('models'),type=Path)
    p.add_argument('--standard-faces',type=int,default=9000)
    p.add_argument('--detailed-faces',type=int,default=40000)
    p.add_argument('--extra-standard-faces',type=int,default=3200)
    p.add_argument('--extra-detailed-faces',type=int,default=11000)
    p.add_argument('--prior-manifest',type=Path,default=None,help='Existing model metadata: preserve every prior structure index')
    p.add_argument('--vertical-axis',choices=['auto','x','y','z'],default='auto')
    p.add_argument('--invert-vertical',action='store_true')
    args=p.parse_args()
    if args.standard_faces<500 or args.detailed_faces<args.standard_faces:
        p.error('Require 500 <= standard faces <= detailed faces.')
    if args.extra_standard_faces<300 or args.extra_detailed_faces<args.extra_standard_faces: p.error('Invalid extra geometry limits.')
    build(args.subset,args.skin,args.out,args.standard_faces,args.detailed_faces,args.vertical_axis,args.invert_vertical,args.extra_standard_faces,args.extra_detailed_faces,args.prior_manifest)

if __name__=='__main__':
    main()
