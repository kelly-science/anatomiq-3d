export function resolveMuscleGroups(structures, definitions=MUSCLE_GROUP_DEFS){
  const nameMap=new Map();
  for(const s of structures){
    if(s.system!=='muscular')continue;
    const name=String(s.name||'').trim().toLowerCase();
    if(!nameMap.has(name))nameMap.set(name,[]);
    nameMap.get(name).push(s);
  }
  return definitions.map(def=>{
    const members=[],missing=[],ambiguous=[];
    for(const name of def.members){
      const matches=nameMap.get(name.toLowerCase())||[];
      if(matches.length===1)members.push(matches[0]);
      else if(matches.length===0)missing.push(name);
      else ambiguous.push(name);
    }
    // Fail closed on an incomplete/ambiguous group: never select a wrong muscle.
    const ready=!missing.length&&!ambiguous.length&&members.length===def.members.length;
    return {...def,members:ready?members:[],missing,ambiguous,ready};
  });
}

export function groupContainsIndex(label,index){
  if(!label||!Number.isInteger(index))return false;
  const members=[label.s,...(Array.isArray(label.g)?label.g.map(a=>a.s):[])];
  return members.some(i=>i===index);
}
